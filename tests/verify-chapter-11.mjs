/** 第十一章：编辑状态、路径补全、浏览位置与本地编辑器。只使用临时文件。 */
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, existsSync, symlinkSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';
import stringWidth from 'string-width';
const root=fileURLToPath(new URL('../',import.meta.url));
const temp=mkdtempSync(join(tmpdir(),'hello-agent-check-11-'));
const previous={cwd:process.cwd(),PATH:process.env.PATH,EDITOR:process.env.EDITOR,VISUAL:process.env.VISUAL};
try {
  writeFileSync(join(temp,'package.json'),'{"type":"module"}');
  symlinkSync(join(root,'node_modules'),join(temp,'node_modules'));
  const source=join(root,'chapter-11-terminal-workbench/05-terminal-layout/src');
  writeFileSync(join(temp,'tsconfig.json'),JSON.stringify({extends:join(root,'tsconfig.json'),compilerOptions:{noEmit:false,noEmitOnError:true,rootDir:source,outDir:join(temp,'dist'),typeRoots:[join(root,'node_modules/@types')]},include:[join(source,'cli.ts')]}));
  execFileSync(process.execPath,[join(root,'node_modules/typescript/bin/tsc'),'-p',join(temp,'tsconfig.json')]);
  const load=(file)=>import(pathToFileURL(join(temp,'dist/ui/tui',file+'.js')));
  const e=await load('editor'), a=await load('input-assist'), v=await load('transcript'), l=await load('layout'), s=await load('system-actions');
  let draft=e.insertText(e.newDraft(),'中文\r\n👨‍👩‍👧‍👦é');
  assert.equal(draft.text,'中文\n👨‍👩‍👧‍👦é');
  draft=e.editKey(draft,'',{backspace:true});assert.equal(draft.text,'中文\n👨‍👩‍👧‍👦');
  draft=e.editKey(draft,'',{backspace:true});assert.equal(draft.text,'中文\n');
  draft=e.editKey(draft,'z',{ctrl:true});assert.equal(draft.text,'中文\n👨‍👩‍👧‍👦');
  draft=e.editKey(draft,'y',{ctrl:true});assert.equal(draft.text,'中文\n');
  assert.equal(e.editKey(e.newDraft('\nx'),'',{home:true}).cursor,1);
  assert.equal(e.editKey({...e.newDraft('\nx'),cursor:0},'',{home:true}).cursor,0);
  assert.equal(e.moveVertical({...e.newDraft('中文\nabcdef'),cursor:2},1),7);
  assert.throws(()=>e.insertText(e.newDraft(),'a'.repeat(e.MAX_DRAFT+1)),/最多/);
  assert.deepEqual(a.searchPrompts(['first','HELLO','first','hello world'],'hello'),['hello world','HELLO']);
  assert.equal(a.commonPrefix(['a😀.ts','a😁.ts']),'a');
  assert.equal((await a.completeInput('/res',4)).text,'/reset');
  const work=join(temp,'project');mkdirSync(work);writeFileSync(join(work,'package.json'),'{}');mkdirSync(join(work,'src'));
  writeFileSync(join(work,'src/中文.ts'),'正文不需要被读取');writeFileSync(join(work,'.env'),'PRIVATE');
  process.chdir(work);
  assert.equal((await a.completeInput('查看 @src/中',9)).text,'查看 @src/中文.ts');
  assert.equal((await a.completeInput('@.en',4)).text,'@.en');
  const aborted=new AbortController();aborted.abort();await assert.rejects(a.completeInput('/res',4,aborted.signal));
  const entries=[{id:'one',label:'Agent',text:'中文🙂'.repeat(40)},{id:'tool',label:'工具',text:'read_file',details:'FULL_RESULT'}];
  const lines=v.transcriptLines(entries,40,new Set());const anchor=lines[2];
  const resized=v.transcriptLines(entries,18,new Set());const start=v.visibleStart(resized,4,anchor);
  assert.equal(resized[start].id,anchor.id);assert.ok(resized[start].offset<=anchor.offset);
  assert.ok(resized[start+1].offset>anchor.offset);
  assert.equal(v.visibleStart([...resized,{id:'new',offset:0,text:'new'}],4,anchor),start);
  assert.ok(!lines.some(line=>line.text.includes('FULL_RESULT')));
  assert.ok(v.transcriptLines(entries,40,new Set(['tool'])).some(line=>line.text==='FULL_RESULT'));
  for(const line of l.wrapLines('中🙂é👨‍👩‍👧‍👦'.repeat(20),7))assert.ok(stringWidth(line.text)<=7);
  for(const line of e.draftLines(e.newDraft('中文🙂'.repeat(80)),12,4))assert.ok(stringWidth(line)<=12);
  const commands=join(temp,'commands');mkdirSync(commands);
  for(const name of ['pbcopy','clip.exe','wl-copy','xclip'])writeFileSync(join(commands,name),'#!/bin/sh\ncat > "$COPY_TARGET"\n',{mode:0o755});
  process.env.PATH=commands+':'+previous.PATH;process.env.COPY_TARGET=join(temp,'clipboard');
  await s.copyText('完整\n结果');assert.equal(readFileSync(process.env.COPY_TARGET,'utf8'),'完整\n结果');
  await assert.rejects(s.copyText('a'.repeat(1_000_001)),/超过/);
  const editor=join(temp,'editor.mjs');
  writeFileSync(editor,"import{writeFileSync}from'node:fs';writeFileSync(process.argv[2],'修改后\\n第二行');writeFileSync(process.env.EDITOR_PATH,process.argv[2]);");
  process.env.VISUAL='';process.env.EDITOR=`${process.execPath} ${editor}`;process.env.EDITOR_PATH=join(temp,'path');
  assert.equal(await s.editExternally('原稿',new AbortController().signal),'修改后\n第二行');
  assert.ok(!existsSync(readFileSync(process.env.EDITOR_PATH,'utf8')),'临时草稿未清理');
  process.env.EDITOR='false';await assert.rejects(s.editExternally('原稿',new AbortController().signal),/原草稿已保留/);
  process.env.EDITOR='sleep 30 #';const stop=new AbortController();const waiting=s.editExternally('原稿',stop.signal);setTimeout(()=>stop.abort(),100);await assert.rejects(waiting,{name:'AbortError'});
  console.log('✓ 第 11 章：多行/Unicode编辑、撤销重做、历史与路径补全、浏览锚点、剪贴板替身、编辑器成功/失败/取消通过');
} finally {
  process.chdir(previous.cwd);
  for(const key of ['PATH','EDITOR','VISUAL'])if(previous[key]===undefined)delete process.env[key];else process.env[key]=previous[key];
  rmSync(temp,{recursive:true,force:true});
}
